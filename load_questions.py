async def load():
    await init_db()
    async with async_session() as session:
        # Check if already loaded
        result = await session.execute(select(Question).limit(1))
        if result.scalar_one_or_none():
            print("Questions already exist in DB. Skipping load.")
            print("To reload, delete the database file first.")
            return
        
        for item in QUESTIONS:
            (cat, diff, quz, qen, qru, ouz, oen, oru, correct, euz, een, eru) = item
            q = Question(
                category=cat,
                difficulty=diff,
                question_uz=quz,
                question_en=qen,
                question_ru=qru,
                options_uz=ouz,
                options_en=oen,
                options_ru=oru,
                correct_index=correct,
                explanation_uz=euz,
                explanation_en=een,
                explanation_ru=eru,
                is_active=True
            )
            session.add(q)
        
        await session.commit()
        print(f"✅ Successfully loaded {len(QUESTIONS)} questions into the database!")


if __name__ == "__main__":
    asyncio.run(load())